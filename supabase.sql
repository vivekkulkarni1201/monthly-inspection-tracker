create policy team_ups_types_all on ups_types for all to anon using (true) with check (true);
drop policy if exists team_issue_types_all on issue_types;
create policy team_issue_types_all on issue_types for all to anon using (true) with check (true);
drop policy if exists team_engineers_all on engineers;
create policy team_engineers_all on engineers for all to anon using (true) with check (true);
drop policy if exists team_monthly_production_all on monthly_production;
create policy team_monthly_production_all on monthly_production for all to anon using (true) with check (true);

