create table if not exists ups_types (
  id bigint generated by default as identity primary key,
  name text unique not null
);
create table if not exists issue_types (
  id bigint generated by default as identity primary key,
  name text unique not null
);
create table if not exists engineers (
  id bigint generated by default as identity primary key,
  name text unique not null
);
create table if not exists monthly_production (
  month text primary key,
  manufactured_qty integer not null default 0
);
create table if not exists inspections (
  id bigint generated by default as identity primary key,
  customer_project text not null,
  qty integer not null default 1,
  kva_rating integer,
  ups_type text,
  engineer text,
  planned_date date,
  revised_date_1 date,
  revised_date_2 date,
  revised_date_3 date,
  revised_date_4 date,
  revised_date_5 date,
  actual_date date,
  status text not null default 'Planned',
  issue_type text,
  issue_at_time text,
  remarks text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table inspections enable row level security;
alter table ups_types enable row level security;
alter table issue_types enable row level security;
alter table engineers enable row level security;
alter table monthly_production enable row level security;

