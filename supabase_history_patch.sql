-- MONTHLY INSPECTION TRACKER - HISTORICAL BACK ENTRY PATCH
-- Run once in Supabase -> SQL Editor.

create table if not exists monthly_history (
  month text primary key,              -- YYYY-MM
  planned_inspections integer not null default 0,
  completed_inspections integer not null default 0,
  ups_offered integer not null default 0,
  ups_completed integer not null default 0,
  manufactured_qty integer not null default 0,
  delayed_qty integer not null default 0,
  cancelled_qty integer not null default 0,
  waiver_qty integer not null default 0,
  remarks text,
  updated_at timestamptz default now()
);

create table if not exists monthly_history_products (
  id bigint generated by default as identity primary key,
  month text not null,
  ups_type text not null,
  qty integer not null default 0,
  unique(month, ups_type)
);

create table if not exists monthly_history_issues (
  id bigint generated by default as identity primary key,
  month text not null,
  issue_type text not null,
  qty integer not null default 0,
  remarks text
);

alter table monthly_history enable row level security;
alter table monthly_history_products enable row level security;
alter table monthly_history_issues enable row level security;

drop policy if exists team_monthly_history_all on monthly_history;
create policy team_monthly_history_all on monthly_history for all to anon using (true) with check (true);

drop policy if exists team_monthly_history_products_all on monthly_history_products;
create policy team_monthly_history_products_all on monthly_history_products for all to anon using (true) with check (true);

drop policy if exists team_monthly_history_issues_all on monthly_history_issues;
create policy team_monthly_history_issues_all on monthly_history_issues for all to anon using (true) with check (true);

do $$ begin
  alter publication supabase_realtime add table monthly_history;
exception when duplicate_object then null; end $$;

do $$ begin
  alter publication supabase_realtime add table monthly_history_products;
exception when duplicate_object then null; end $$;

do $$ begin
  alter publication supabase_realtime add table monthly_history_issues;
exception when duplicate_object then null; end $$;
